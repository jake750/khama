#!/bin/sh
# Rebuilds CHANGELOG.md from the commits between release tags (M-18).
# The same filter as the "What's new" step in build.yml.
# `scripts/changelog.sh 1.2.3` also adds the commits since the last tag as 1.2.3
# (release.mjs does this, because CI creates the tag only after the build).
set -e
cd "$(dirname "$0")/.."
{
  echo "# Changelog · سجل التغييرات"
  echo
  echo "Generated by \`scripts/changelog.sh\` from the commit messages. Each release on GitHub carries the same list."
  echo
  last=$(git describe --tags --abbrev=0 --match 'v*' 2>/dev/null || true)
  if [ -n "$1" ] && [ "v$1" != "$last" ]; then
    echo "## $1 ($(date +%F))"
    echo
    git log --no-merges --pretty='- %s' ${last:+$last..}HEAD | grep -v -e '^- REMAINING' -e '^- الإصدار' || true
    echo
  fi
  prev=""
  for tag in $(git tag -l 'v*' --sort=-v:refname) ""; do
    if [ -n "$prev" ]; then
      date=$(git log -1 --format=%as "$prev")
      echo "## ${prev#v} ($date)"
      echo
      git log --no-merges --pretty='- %s' ${tag:+$tag..}"$prev" | grep -v -e '^- REMAINING' -e '^- الإصدار' || true
      echo
    fi
    prev=$tag
  done
} > CHANGELOG.md
