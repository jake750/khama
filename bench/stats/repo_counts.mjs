#!/usr/bin/env node
// Counts quoted in the report that come from the repository itself (review items R3-A13, R3-A23, R3-A46).
//   node bench/stats/repo_counts.mjs [ref]      (ref defaults to HEAD; run it again on the defense tag)
// Prints lines of code per language, test counts, and commit counts from git: total, with the
// "Co-Authored-By: Claude" trailer, per day and per area of the repository. Standard library only.
import { execFileSync } from "node:child_process";

const root = new URL("../..", import.meta.url).pathname.replace(/^\/([A-Z]:)/, "$1");
const ref = process.argv[2] ?? "HEAD";
const git = (...a) => execFileSync("git", ["-C", root, ...a], { encoding: "utf8", maxBuffer: 1 << 28 });

// ---------- code (files tracked by git at <ref>, so a tag can be counted without checking it out) ----------
const lines = {};
let rustTests = 0,
  rustIgnored = 0,
  tsExports = 0,
  uiTests = 0,
  uiFiles = 0,
  i18nLines = 0;
const tracked = git("ls-tree", "-r", "--name-only", ref, "--", "src", "src-tauri/src").trim().split("\n");
for (const file of tracked) {
  const ext = file.split(".").pop();
  if (!["ts", "tsx", "css", "rs"].includes(ext)) continue;
  const text = git("show", `${ref}:${file}`);
  const n = text.split("\n").length - (text.endsWith("\n") ? 1 : 0);
  const lang = ext === "rs" ? "Rust" : ext === "css" ? "CSS" : "TypeScript";
  lines[lang] = (lines[lang] ?? 0) + n;
  if (file === "src/i18n.ts") i18nLines = n;
  if (ext === "rs") {
    rustTests += (text.match(/#\[test\]/g) ?? []).length;
    rustIgnored += (text.match(/#\[ignore/g) ?? []).length;
    tsExports += (text.match(/ts\(export/g) ?? []).length;
  }
  if (/\.test\.tsx?$/.test(file)) {
    uiFiles++;
    uiTests += (text.match(/^\s*(it|test)(\.each\([^)]*\))?\(/gm) ?? []).length;
  }
}
const total = Object.values(lines).reduce((a, b) => a + b, 0);
console.log(
  `code at ${ref}: ${total} lines (${Object.entries(lines)
    .map(([k, v]) => `${k} ${v}`)
    .join(", ")}); src/i18n.ts ${i18nLines}`,
);
console.log(
  `tests: Rust #[test] ${rustTests} (of which #[ignore] ${rustIgnored}), plus ${tsExports} generated by ts-rs (#[ts(export)]); UI it()/test() calls ${uiTests} in ${uiFiles} files`,
);

// ---------- commits ----------
// --numstat gives "added<TAB>deleted<TAB>path" per file ("-" for binary files)
const log = git("log", ref, "--no-merges", "--date=short", "--format=%x1e%h%x1f%ad%x1f%s%x1f%B%x1f", "--numstat")
  .split("\x1e")
  .filter(Boolean)
  .map((c) => {
    const [hash, date, subject, body, stat] = c.split("\x1f");
    const files = (stat ?? "")
      .trim()
      .split("\n")
      .filter(Boolean)
      .map((l) => {
        const [a, , f] = l.split("\t");
        return { path: f, added: Number(a) || 0 };
      });
    return { hash, date, subject, claude: /Co-Authored-By: Claude/i.test(body), files };
  });
const claude = log.filter((c) => c.claude).length;
const releases = log.filter((c) => !c.claude && /^الإصدار \d/.test(c.subject)).length;
console.log(
  `commits (no merges): ${log.length}, with the Claude co-author trailer: ${claude} (${Math.round((100 * claude) / log.length)} %); ` +
    `without it: ${log.length - claude}, of which ${releases} are release commits written by scripts/release (version bump only)`,
);

const byDay = {};
for (const c of log) byDay[c.date] = (byDay[c.date] ?? 0) + 1;
console.log(
  "per day: " +
    Object.keys(byDay)
      .sort()
      .map((d) => `${d.slice(5)} ${byDay[d]}`)
      .join(", "),
);

const areas = [
  ["Rust core (src-tauri/src)", /^src-tauri\/src\//],
  ["interface (src)", /^src\//],
  ["Android (src-tauri/gen, *.kt)", /^src-tauri\/gen\/|\.kt$/],
  ["CI and scripts (.github, scripts)", /^\.github\/|^scripts\//],
  ["bench (research scripts and results)", /^bench\//],
  ["report (docs/report)", /^docs\/report\//],
  ["other docs (docs, *.md)", /^docs\/(?!report\/)|^[^/]+\.md$/],
];
for (const [name, re] of areas) {
  const touched = log.filter((c) => c.files.some((f) => re.test(f.path)));
  const withClaude = touched.filter((c) => c.claude).length;
  const added = (cs) => cs.reduce((s, c) => s + c.files.filter((f) => re.test(f.path)).reduce((a, f) => a + f.added, 0), 0);
  const all = added(touched);
  const byClaude = added(touched.filter((c) => c.claude));
  console.log(
    `  ${name}: ${touched.length} commits, ${withClaude} with the trailer; lines added ${all}, ` +
      `${byClaude} of them in commits with the trailer (${all ? Math.round((100 * byClaude) / all) : 0} %)`,
  );
}

const periods = [
  ["2026-11-07", "2026-11-13", "build: first version, Android, redesign"],
  ["2026-11-14", "2026-11-18", "first review and fixes (0.3.4-0.3.16)"],
  ["2026-11-19", "2026-12-31", "research axes, Reels path, later reviews"],
];
for (const [from, to, name] of periods) {
  const n = log.filter((c) => c.date >= from && c.date <= to).length;
  console.log(`  ${from}..${to} ${name}: ${n} commits`);
}
